//! math::svdInverse (UnityPlayer.dll 0x180ec87f0): the inverse of a 3x3 matrix by five rounds of Jacobi SVD (quaternion rotations built
//! with rsqrtps and one Newton step), taken by ParticleSystemTempData::SetMatrices when the camera matrix's determinant is not above 1e-6
//! (NaN included: a non-finite camera rotation from a hand-edited shakeIntensity preference).
//! Written instruction for instruction from the disassembly (the decompile loses SSE lanes): `x[n]` is xmmN as four u32 lanes, `mem` the
//! stack frame (rbp = rax - 0xdb8, rsp = rbp - 0x100, r11 = rax - 8; 16-byte slots), constants are the 16-byte rodata operands, `inp`/`out`
//! the float3x3 rows at rdx / rcx. `tests::match_unityplayer` checks it against the DLL's own machine code (tools/native_svd.py).
#![allow(unused_assignments, unused_mut, clippy::all)]
use super::sse::{rcp, rsqrt};

type V = [u32; 4];
fn f(x: u32) -> f32 {
    f32::from_bits(x)
}
fn lanes1(a: V, g: impl Fn(u32) -> u32) -> V {
    [g(a[0]), g(a[1]), g(a[2]), g(a[3])]
}
fn lanes2(a: V, b: V, g: impl Fn(u32, u32) -> u32) -> V {
    [g(a[0], b[0]), g(a[1], b[1]), g(a[2], b[2]), g(a[3], b[3])]
}
fn fl(a: V, b: V, g: impl Fn(f32, f32) -> f32) -> V {
    lanes2(a, b, |p, q| g(f(p), f(q)).to_bits())
}
/// mulps / addps / subps: a NaN operand comes back quieted, the first operand's when both are NaN (the compiler may swap the operands of
/// a commutative Rust op, which would change which NaN, so it is decided here).
fn arith(a: V, b: V, g: impl Fn(f32, f32) -> f32) -> V {
    lanes2(a, b, |p, q| {
        if f(p).is_nan() {
            p | 0x40_0000
        } else if f(q).is_nan() {
            q | 0x40_0000
        } else {
            x86(g(f(p), f(q)))
        }
    })
}
/// A NaN made from non-NaN operands (0 * inf, inf - inf, sqrt of a negative) is the x86 default NaN 0xffc00000; ARM's
/// would be 0x7fc00000.
fn x86(r: f32) -> u32 {
    if r.is_nan() { 0xffc0_0000 } else { r.to_bits() }
}
fn mulps(a: V, b: V) -> V {
    arith(a, b, |p, q| p * q)
}
fn addps(a: V, b: V) -> V {
    arith(a, b, |p, q| p + q)
}
fn subps(a: V, b: V) -> V {
    arith(a, b, |p, q| p - q)
}
/// minps / maxps: the second operand when either is NaN.
fn minps(a: V, b: V) -> V {
    fl(a, b, |p, q| if p < q { p } else { q })
}
fn maxps(a: V, b: V) -> V {
    fl(a, b, |p, q| if p > q { p } else { q })
}
fn cmpltps(a: V, b: V) -> V {
    lanes2(a, b, |p, q| if f(p) < f(q) { !0 } else { 0 })
}
fn cmpeqps(a: V, b: V) -> V {
    lanes2(a, b, |p, q| if f(p) == f(q) { !0 } else { 0 })
}
fn psubd(a: V, b: V) -> V {
    lanes2(a, b, |p, q| p.wrapping_sub(q))
}
fn unpcklps(a: V, b: V) -> V {
    [a[0], b[0], a[1], b[1]]
}
fn unpckhps(a: V, b: V) -> V {
    [a[2], b[2], a[3], b[3]]
}
fn movlhps(a: V, b: V) -> V {
    [a[0], a[1], b[0], b[1]]
}
fn movhlps(a: V, b: V) -> V {
    [b[2], b[3], a[2], a[3]]
}

