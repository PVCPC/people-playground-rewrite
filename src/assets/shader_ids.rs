//! The shaders' path ids as the code knows them (1.28.41's), by file and name. Other builds renumber them (1.28.52: TwoSidedUnlit
//! 130 -> 134, AdditiveGlowSprite 891 -> 895, ProceduralShatter 81 -> 82): `AssetDb::shader_id` maps a shader back to
//! its 1.28.41 id through this table.

/// A Shader object's name: its SerializedShader m_Name, taken as the first length-prefixed printable string holding a
/// '/'. ponytail: a scan, not a SerializedShader parse; checked against every shader in these three files of 1.28.41,
/// 1.28.52 and 1.28.53 (one name each, no repeats), and wrong for globalgamemanagers' HeatEffect, which this table leaves out.
pub fn shader_name(d: &[u8]) -> Option<&str> {
    (4..d.len()).find_map(|p| {
        let n = i32::from_le_bytes(d[p - 4..p].try_into().unwrap());
        let s = d.get(p..p + usize::try_from(n).ok().filter(|&n| n >= 3)?)?;
        (s.iter().all(|c| (b' '..=b'~').contains(c)) && s.contains(&b'/')).then(|| std::str::from_utf8(s).unwrap())
    })
}

